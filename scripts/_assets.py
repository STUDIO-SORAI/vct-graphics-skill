"""Asset preflight + friendly errors. Third-party assets (logos, fonts, photos) are NOT
shipped with this repo; see assets/README.md for what to drop in and where."""
import os, sys, subprocess

NOTO = ['/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc', '/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc']
BG_ARG = {'bg_pac': 'pac', 'bg_eu': 'eu', 'bg_euam': 'euam'}
HELP = "See assets/README.md for the exact files to drop in."


def die(msg):
    sys.stderr.write('\nERROR: ' + msg + '\n' + HELP + '\n')
    sys.exit(2)


def _bg(root, name, S):
    """Backgrounds are generated by scripts/bg.py; create them on demand."""
    out = '%s/assets/%s%s.png' % (root, name, '@2x' if S == 2 else '')
    if not os.path.exists(out):
        os.makedirs(os.path.dirname(out), exist_ok=True)
        here = os.path.dirname(os.path.abspath(__file__))
        r = subprocess.run([sys.executable, here + '/bg.py', BG_ARG[name], str(S), out])
        if r.returncode:
            die('could not generate background ' + out)


def preflight(kind, root):
    S = 2 if len(sys.argv) > 2 and sys.argv[2] == '2' else 1
    a = root + '/assets/'
    need = [a + 'fonts/ClashDisplay/ClashDisplay-Bold.otf', a + 'fonts/ClashDisplay/ClashDisplay-Semibold.otf',
            a + 'vct_white.png', a + 'sorai_logo_on_dark.png'] + NOTO
    if kind == 'pac':
        need.append(a + 'pacific_kickoff_white.png'); _bg(root, 'bg_pac', S)
    elif kind == 'cover':
        need += [a + 'cover/logo_pac.png', a + 'cover/logo_emea.png', a + 'cover/logo_amer.png']; _bg(root, 'bg_pac', S)
    else:  # reg / kick_pac
        reg = os.environ.get('REG')
        if reg not in ('pac', 'emea', 'amer'):
            die('set REG=pac|emea|amer, e.g.  REG=emea python3 scripts/%s.py <mode> <S> <out.png>' % kind)
        need.append(a + {'pac': 'pacific', 'emea': 'europe', 'amer': 'americas'}[reg] + '_kickoff_white.png')
        _bg(root, {'pac': 'bg_pac', 'emea': 'bg_eu', 'amer': 'bg_euam'}[reg], S)
    missing = [p for p in need if not os.path.exists(p)]
    if missing:
        die('missing required asset file(s):\n  ' + '\n  '.join(missing))
    _install_hook()


def _install_hook():
    old = sys.excepthook

    def hook(t, e, tb):
        if issubclass(t, FileNotFoundError) and getattr(e, 'filename', None):
            sys.stderr.write('\nERROR: missing asset file: %s\n%s\n' % (e.filename, HELP))
            sys.exit(2)
        if issubclass(t, OSError) and 'cannot open resource' in str(e):
            sys.stderr.write('\nERROR: a font could not be opened (%s). Check assets/README.md (fonts).\n' % e)
            sys.exit(2)
        old(t, e, tb)
    sys.excepthook = hook
